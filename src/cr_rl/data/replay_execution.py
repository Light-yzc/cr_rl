"""Run repaired source events on the real decision grid and label the live states.

Hand rearrangements are absent from a native replay's command log. These rows
must therefore be captured here, never regenerated by the native labeller.
"""

from __future__ import annotations

import hashlib
from collections import Counter, deque
from dataclasses import dataclass

import numpy as np

from cr_rl.data.replay_repair import nearest_legal_action


@dataclass(frozen=True)
class ExecutionConfig:
    decision_ticks: int = 5
    repair_hand: bool = False
    max_hand_repairs: int = -1  # -1 explicitly means unlimited.
    repair_tile: bool = False
    max_tile_shift: int = 2
    repair_time: bool = False
    time_tolerance_ticks: int = 4
    max_delay_ticks: int = 200
    max_omissions: int = 0
    allow_omitted_suffix: bool = False
    skip_unavailable_abilities: bool = False
    capture_rows: bool = True
    source_end_tick: int | None = None

    def __post_init__(self):
        if self.decision_ticks < 1 or self.max_hand_repairs < -1:
            raise ValueError("Invalid decision interval or hand repair budget")
        if (
            min(
                self.max_tile_shift,
                self.time_tolerance_ticks,
                self.max_delay_ticks,
                self.max_omissions,
            )
            < 0
        ):
            raise ValueError("Repair tolerances cannot be negative")


def _normalise(value):
    return "".join(c for c in value.lower() if c.isalnum())


def _field(vector, seat, key):
    return vector.observations[0, seat, list(vector.schema.header[key])]


def source_event_keys(event):
    keys = event.get("deck_card_key_candidates") or []
    if not keys and event.get("card_key"):
        keys = [event["card_key"]]
    if not keys and event.get("kind") != "play_card":
        keys = event.get("ability_source_candidates") or []
    return list(dict.fromkeys(keys))


def _pending(vector):
    for seat in (0, 1):
        if any(_field(vector, seat, "hand_pending")):
            return True
        if "ability_command_ticks" in vector.schema.header:
            if any(_field(vector, seat, "ability_command_ticks") > 0):
                return True
    return False


def _request(
    vector, event, seat, card, config, runtime_decks, records, hand_repairs, native_observer=None
):
    """Resolve one FIFO head against the current native mask."""
    if event["kind"] != "play_card":
        wanted = {_normalise(c) for c in card}
        native_mapping = native_observer is not None and hasattr(native_observer, "ability_slots")
        if native_mapping:
            slots = native_observer.ability_slots(seat=seat)
            matches = [
                slot
                for slot in slots
                if wanted.intersection(_normalise(name) for name in slot.get("card_candidates", []))
            ]
            possible = [
                slot
                for slot in matches
                if slot["available"] and vector.masks[0, seat, slot["action"]]
            ]
        else:
            # Pure test vectors need no JVM bridge. Production always uses
            # native source-card identity, not a card-name/unit-name heuristic.
            slots, matches, possible = [], [], []
            for slot, champion in enumerate(_field(vector, seat, "ability_champion")):
                name = vector.vocabulary[int(champion)] if int(champion) >= 0 else ""
                action = 2305 + slot
                row = {
                    "slot": slot,
                    "action": action,
                    "champion": name,
                    "card": name,
                    "card_candidates": [name],
                    "available": bool(vector.masks[0, seat, action]),
                    "mapping_source": "non_native_test_vector",
                }
                slots.append(row)
                if _normalise(name).replace("hero", "") in {
                    name.replace("hero", "") for name in wanted
                }:
                    matches.append(row)
                    if row["available"]:
                        possible.append(row)
        if len(possible) == 1:
            resolved = possible[0]
            detail = {"ability_slot": resolved, "candidate_cards": card}
            if native_mapping or not event.get("ability_source_authoritative", True):
                records.append(
                    {
                        "category": "ability_source_resolution",
                        "candidate_cards": card,
                        "resolved_card": resolved.get("card"),
                        "native_champion": resolved.get("champion"),
                        "mapping_source": resolved["mapping_source"],
                        "executed_action": resolved["action"],
                        "detail": "unique matching native legal ability slot",
                    }
                )
            return resolved["action"], None, detail
        detail = {
            "candidate_cards": card,
            "native_slots": slots,
            "matching_slots": len(matches),
            "legal_matching_slots": len(possible),
        }
        # Keep the established broad reason for old report consumers; preserve
        # the exact identity/gate distinction in the final event's diagnostics.
        detail["ability_failure"] = (
            "multiple_legal_slots"
            if len(possible) > 1
            else "matching_slot_closed"
            if matches
            else "no_matching_card_identity"
        )
        return None, "ability_unavailable_or_ambiguous", detail

    xy = (event.get("coordinates") or {}).get("native_world_units")
    if not xy or "x" not in xy or "y" not in xy:
        return None, "missing_coordinates", None
    x, y = int(xy["x"]), int(xy["y"])
    sx, sy = (18000 - x, y) if seat == 0 else (x, 32000 - y)
    raw_col, raw_row = sx // 1000, sy // 1000
    col, row = max(0, min(17, raw_col)), max(0, min(31, raw_row))
    clamp_distance = abs(col - raw_col) + abs(row - raw_row)
    if clamp_distance and (not config.repair_tile or clamp_distance > config.max_tile_shift):
        return None, "coordinates_out_of_bounds", None
    card_id = vector.card_id(card)
    hand = [int(c) for c in _field(vector, seat, "hand_card")]
    if card_id not in hand:
        allowed = config.max_hand_repairs < 0 or hand_repairs < config.max_hand_repairs
        if not config.repair_hand or not allowed:
            return None, "not_in_hand", None
        from cr_rl.data.opening_cycle import force_card_into_hand

        try:
            # This is the native deck index after opening-cycle reordering.
            change = force_card_into_hand(
                vector, seat, runtime_decks[seat].index(card), return_record=True
            )
        except ValueError as error:
            return None, "hand_temporarily_unavailable", str(error)
        records.append({"category": "hand_replacement", **change})
        hand = [int(c) for c in _field(vector, seat, "hand_card")]
        if card_id not in hand:
            raise RuntimeError("Live hand repair did not expose the requested card")
    action = vector.schema.play(hand.index(card_id), col, row)
    if vector.masks[0, seat, action]:
        if clamp_distance:
            records.append(
                {
                    "category": "coordinate_clamp",
                    "source_tile": [raw_col, raw_row],
                    "executed_tile": [col, row],
                    "distance": abs(col - raw_col) + abs(row - raw_row),
                }
            )
        return int(action), None, {"requested_action": int(action), "source_xy": [x, y]}
    candidate = (
        nearest_legal_action(action, vector.masks[0, seat], config.max_tile_shift - clamp_distance)
        if config.repair_tile
        else None
    )
    if candidate:
        executed, distance = candidate
        distance += clamp_distance
        records.append(
            {
                "category": "tile_snap",
                "requested_action": int(action),
                "executed_action": int(executed),
                "distance": distance,
            }
        )
        return int(executed), None, {"requested_action": int(action), "source_xy": [x, y]}
    slot = hand.index(card_id)
    if bool(_field(vector, seat, "hand_pending")[slot]):
        return None, "hand_pending", None
    # A slot with no legal tile is commonly closed by elixir or start cooldown.
    return None, "mask_closed", None


def execute_repaired_events(
    vector, events, decks, deck_keys, runtime_decks, config, *, native_observer=None
):
    """Execute source events once, preserving per-seat order and actual pre-action rows.

    The vector must use ``config.decision_ticks`` and autoreset must be disabled.
    No elixir is injected; a closed mask may be retried until the declared delay
    budget. Completion means every source event was successfully submitted and
    all pending commands settled without a native run refusal.
    """
    queues = [deque(), deque()]
    ledger, omitted, executed = [], [], []
    skipped = Counter()
    all_events = []
    for source_tick in sorted(events):
        for event in events[source_tick]:
            item = {"event": event, "source_tick": int(source_tick), "id": len(all_events)}
            all_events.append(item)
            if event.get("side") not in ("team", "opponent"):
                item["invalid_side"] = True
                queues[0].append(item)
            else:
                queues[0 if event["side"] == "team" else 1].append(item)
    obs, masks, labels, times, seats, flags = [], [], [], [], [], []
    hand_repairs, submitted = 0, 0
    collision_windows = Counter()
    for item in all_events:
        seat = 0 if item["event"].get("side") == "team" else 1
        window = (
            (item["source_tick"] + config.decision_ticks - 1)
            // config.decision_ticks
            * config.decision_ticks
        )
        collision_windows[(window, seat)] += 1
    collisions = sum(max(0, count - 1) for count in collision_windows.values())
    source_last = max(events, default=0)
    pending_end = None
    run_refusals = []
    command_sources = {}
    inflight = [set(), set()]
    native_state = native_observer.poll() if native_observer else None
    native_successes = set()
    fatal_run_refusal = False
    target_end = max(source_last, config.source_end_tick or 0)
    hard_end = target_end + config.max_delay_ticks + max(100, len(all_events) * 5)
    last_submission_tick = None
    stop_reason = "native_terminal"
    decision = config.decision_ticks
    # The native vector stores elapsed tick in info, so do not infer it from loop count.
    while not vector.dones[0]:
        tick = int(vector.info(0)["tick"])
        if tick > hard_end:
            skipped["global_time_budget"] += max(1, sum(len(q) for q in queues))
            stop_reason = "global_time_budget"
            break
        actions = np.zeros((1, 2), dtype=np.int32)
        chosen = []
        for seat, queue in enumerate(queues):
            # Await native confirmation before the next source command of this
            # seat; a retry must not overtake a later already-issued command.
            if native_observer and config.repair_time and inflight[seat]:
                continue
            while queue and queue[0]["source_tick"] <= tick:
                item = queue[0]
                source_tick, event = item["source_tick"], item["event"]
                delta = tick - source_tick
                if "attempted_tick" not in item:
                    item["attempted_tick"] = tick
                reason, details = None, None
                if item.get("invalid_side"):
                    reason = "unknown_side"
                keys = source_event_keys(event)
                indices = [i for i, key in enumerate(deck_keys[seat]) if key in keys]
                index = indices[0] if indices else None
                if index is None:
                    reason = reason or "card_not_in_deck"
                if source_tick < 0:
                    reason = "negative_source_tick"
                if delta and not config.repair_time:
                    reason = "time_misaligned"
                if delta > config.max_delay_ticks:
                    reason = "delay_budget_exhausted"
                if 0 < delta < decision and delta > config.time_tolerance_ticks:
                    reason = "time_misaligned"
                changes = []
                if reason is None:
                    action, reason, details = _request(
                        vector,
                        event,
                        seat,
                        (
                            [decks[seat][i] for i in indices]
                            if event["kind"] != "play_card"
                            else decks[seat][index]
                        ),
                        config,
                        runtime_decks,
                        changes,
                        hand_repairs,
                        native_observer=native_observer,
                    )
                    for change in changes:
                        change.update(
                            event_id=item["id"],
                            source_tick=source_tick,
                            simulator_tick=tick,
                            seat=seat,
                            card=decks[seat][index],
                        )
                        ledger.append(change)
                        hand_repairs += change["category"] == "hand_replacement"
                    if action is not None:
                        queue.popleft()
                        actions[0, seat] = action
                        chosen.append((seat, item, action, details))
                        if delta:
                            ledger.append(
                                {
                                    "category": "time_snap" if delta < decision else "time_delay",
                                    "event_id": item["id"],
                                    "source_tick": source_tick,
                                    "simulator_tick": tick,
                                    "seat": seat,
                                    "delta_ticks": delta,
                                }
                            )
                        break
                permanent = reason in {
                    "unknown_side",
                    "card_not_in_deck",
                    "missing_coordinates",
                    "coordinates_out_of_bounds",
                    "negative_source_tick",
                    "time_misaligned",
                    "delay_budget_exhausted",
                }
                if (
                    config.repair_time
                    and not permanent
                    and delta + decision <= config.max_delay_ticks
                ):
                    item["last_wait_reason"] = reason
                    item["last_wait_detail"] = details
                    break
                queue.popleft()
                if reason == "ability_unavailable_or_ambiguous" and config.skip_unavailable_abilities:
                    skipped[reason] += 1
                    ledger.append(
                        {
                            "category": "ability_skipped",
                            "reason": reason,
                            "detail": details or item.get("last_wait_detail"),
                            "event_id": item["id"],
                            "source_tick": source_tick,
                            "simulator_tick": tick,
                            "seat": seat,
                            "accepted": False,
                            "supervised": False,
                        }
                    )
                    continue
                skipped[reason] += 1
                omitted.append((tick, seat))
                ledger.append(
                    {
                        "category": "rejected",
                        "reason": reason,
                        "detail": details or item.get("last_wait_detail"),
                        "last_wait_reason": item.get("last_wait_reason"),
                        "event_id": item["id"],
                        "source_tick": source_tick,
                        "simulator_tick": tick,
                        "seat": seat,
                        "accepted": False,
                    }
                )
                if len(omitted) > config.max_omissions and not config.allow_omitted_suffix:
                    break
            if len(omitted) > config.max_omissions and not config.allow_omitted_suffix:
                break
        if len(omitted) > config.max_omissions and not config.allow_omitted_suffix:
            # Neither seat's simultaneous command is submitted on an aborted decision.
            for seat, item, _, _ in chosen:
                queues[seat].appendleft(item)
            stop_reason = "omission_budget_exhausted"
            break
        # Both hand mutations have happened before either seat's state is captured.
        state_hash = hashlib.sha256(
            vector.observations[0].tobytes() + vector.masks[0].tobytes()
        ).hexdigest()
        if config.capture_rows:
            obs.append(vector.observations[0].copy())
            masks.append(vector.masks[0].copy())
            labels.append(actions[0].copy())
            times.extend([tick, tick])
            seats.extend([0, 1])
            from cr_rl.data.replay_supervision import GENERATED_WAIT_TAIL

            horizon = config.source_end_tick if config.source_end_tick is not None else source_last
            flags.extend(
                [
                    GENERATED_WAIT_TAIL if tick > horizon and not actions[0, seat] else 0
                    for seat in (0, 1)
                ]
            )
        vector.actions[:] = actions
        vector.step()
        info = vector.info(0)
        if int(info["tick"]) <= tick and not vector.dones[0]:
            stop_reason = "simulator_clock_stalled"
            break
        polled = native_observer.poll() if native_observer else None
        for seat, item, action, details in chosen:
            refused = bool(info.get(f"illegal_{seat}", 0))
            record = {
                "category": "execution",
                "event_id": item["id"],
                "source_tick": item["source_tick"],
                "simulator_tick": tick,
                "seat": seat,
                "executed_action": int(action),
                "accepted": not refused,
                "execution_status": "submission_refused" if refused else "submitted",
                "pre_state_sha256": state_hash,
                "post_state_sha256": hashlib.sha256(
                    vector.observations[0].tobytes() + vector.masks[0].tobytes()
                ).hexdigest(),
                "source_event": item["event"],
                "wait_reason": item.get("last_wait_reason"),
                **(details or {}),
            }
            ledger.append(record)
            if refused:
                skipped["native_submission_refused"] += 1
                omitted.append((tick, seat))
                if config.capture_rows:
                    flags[-2 + seat] |= 1
            else:
                submitted += 1
                last_submission_tick = tick
                if native_observer:
                    commands = [c for c in polled["new_commands"] if c["seat"] == seat]
                    if len(commands) != 1:
                        raise RuntimeError("Cannot uniquely match native command to source event")
                    command = commands[0]
                    record["native_command_name"] = command["name"]
                    record["native_run_tick"] = command["run_tick"]
                    command_sources[command["name"]] = {
                        "item": item,
                        "record": record,
                        "row": len(flags) - 2 + seat,
                        "submission_tick": tick,
                        "seat": seat,
                    }
                    inflight[seat].add(command["name"])
                else:
                    executed.append((tick, item["event"]["kind"] != "play_card"))
        if native_observer:
            native_state = polled
            for result in polled["new_results"]:
                source = command_sources.get(result["name"])
                if source is None:
                    raise RuntimeError("Native execution has no corresponding source event")
                item, seat = source["item"], source["seat"]
                inflight[seat].discard(result["name"])
                source["record"]["execution_status"] = (
                    "confirmed" if result["success"] else "native_run_refused"
                )
                source["record"]["native_success"] = bool(result["success"])
                source["record"]["actual_run_tick"] = result["tick"]
                ledger.append(
                    {
                        "category": "native_run",
                        "event_id": item["id"],
                        "source_tick": item["source_tick"],
                        "simulator_tick": int(info["tick"]),
                        **result,
                    }
                )
                if result["success"]:
                    native_successes.add(item["id"])
                    executed.append(
                        (source["submission_tick"], item["event"]["kind"] != "play_card")
                    )
                else:
                    from cr_rl.data.replay_supervision import SOURCE_COMMAND_OMITTED

                    if config.capture_rows:
                        flags[source["row"]] |= SOURCE_COMMAND_OMITTED
                    failure = {
                        "event_id": item["id"],
                        "simulator_tick": int(info["tick"]),
                        **result,
                        "retried": False,
                    }
                    run_refusals.append(failure)
                    if config.skip_unavailable_abilities and item["event"]["kind"] != "play_card":
                        skipped["native_run_" + str(result["refusal"])] += 1
                        fatal_run_refusal = False
                        continue
                    can_retry = (
                        config.repair_time
                        and result["retryable"]
                        and not polled["match_decided"]
                        and int(info["tick"]) - item["source_tick"] < config.max_delay_ticks
                    )
                    if can_retry:
                        failure["retried"] = True
                        item["last_wait_reason"] = result["refusal"]
                        queues[seat].appendleft(item)
                        ledger.append(
                            {
                                "category": "native_retry",
                                "event_id": item["id"],
                                "source_tick": item["source_tick"],
                                "simulator_tick": int(info["tick"]),
                                "seat": seat,
                                "reason": result["refusal"],
                            }
                        )
                    else:
                        fatal_run_refusal = True
                        omitted.append((source["submission_tick"], seat))
                        skipped["native_run_" + str(result["refusal"])] += 1
        else:
            for seat in (0, 1):
                for key in ("last_run_refusal", "last_ability_run_refusal"):
                    codes = _field(vector, seat, key)
                    if any(codes):
                        run_refusals.append(
                            {
                                "seat": seat,
                                "simulator_tick": int(info["tick"]),
                                "category": key,
                                "code": int(codes[0]),
                            }
                        )
        if info.get("fault", 0) or fatal_run_refusal or (run_refusals and not native_observer):
            stop_reason = "native_fault" if info.get("fault", 0) else "native_run_refusal"
            # A refusal is delayed: conservatively mask the corresponding seat's
            # recent command window, including the original pre-action row.
            from cr_rl.data.replay_supervision import SOURCE_COMMAND_OMITTED

            for refusal in [] if native_observer else run_refusals:
                since = refusal["simulator_tick"] - int(vector.schema.play_delay_ticks) - decision
                for row in range(len(flags)):
                    if seats[row] == refusal["seat"] and times[row] >= since:
                        flags[row] |= SOURCE_COMMAND_OMITTED
            break
        if len(omitted) > config.max_omissions and not config.allow_omitted_suffix:
            break
        if native_state and native_state.get("match_ended", native_state["match_decided"]):
            stop_reason = "native_match_decided"
            break
        if not any(queues) and not any(inflight):
            if pending_end is None:
                pending_end = tick + max(
                    2 * decision, int(vector.schema.play_delay_ticks) + decision
                )
            pending = native_state["pending_count"] > 0 if native_state else _pending(vector)
            if not pending and int(info["tick"]) >= max(pending_end, target_end):
                stop_reason = "source_horizon_reached"
                break
    info = vector.info(0)
    fault = bool(info.get("fault", 0))
    pending = native_state["pending_count"] > 0 if native_state else _pending(vector)
    settled = (
        not pending
        and not any(inflight)
        and (
            native_observer is not None
            or last_submission_tick is None
            or int(info["tick"]) >= last_submission_tick + int(vector.schema.play_delay_ticks)
        )
    )
    successful_events = len(native_successes) if native_observer else len(executed)
    complete = (
        successful_events == len(all_events)
        and bool(all_events)
        and not omitted
        and not fault
        and (not fatal_run_refusal if native_observer else not run_refusals)
        and settled
        and stop_reason != "global_time_budget"
    )
    decided = bool(native_state and native_state["match_decided"])
    native_winner = native_state.get("winner") if native_state else None
    normal_terminal = (
        decided
        and native_state.get("match_ended") is True
        and native_winner in (0, 1)
        and not fault
        and not bool(info.get("truncated", 0))
    )
    source_or_terminal = bool(complete or normal_terminal)
    unfinished_reason = "terminal_before_event" if vector.dones[0] or decided else stop_reason
    final_ids = {r["event_id"] for r in ledger if r["category"] in ("execution", "rejected")}
    for item in all_events:
        if item["id"] not in final_ids:
            seat = 0 if item["event"].get("side") == "team" else 1
            ledger.append(
                {
                    "category": "rejected",
                    "event_id": item["id"],
                    "seat": seat,
                    "source_tick": item["source_tick"],
                    "simulator_tick": int(info["tick"]),
                    "accepted": False,
                    "reason": unfinished_reason,
                }
            )
    if native_observer:
        from cr_rl.data.replay_supervision import SOURCE_COMMAND_OMITTED

        for source in command_sources.values():
            if source["record"]["execution_status"] == "submitted":
                source["record"]["execution_status"] = "unconfirmed_at_stop"
                if config.capture_rows:
                    flags[source["row"]] |= SOURCE_COMMAND_OMITTED
    if not settled and config.capture_rows:
        from cr_rl.data.replay_supervision import SOURCE_COMMAND_OMITTED

        since = int(info["tick"]) - int(vector.schema.play_delay_ticks) - decision
        for row in range(len(flags)):
            if times[row] >= since:
                flags[row] |= SOURCE_COMMAND_OMITTED
    repair_records = [
        r for r in ledger if r["category"] not in ("execution", "rejected", "native_run")
    ]
    categories = Counter(r["category"] for r in repair_records)
    stats = {
        "used": successful_events,
        "used_abilities": sum(a for _, a in executed),
        "submitted_commands": submitted,
        "native_successful_commands": successful_events if native_observer else None,
        "execution_confirmation": "native_command_results"
        if native_observer
        else "header_and_drain",
        "processed_source_events": len(
            {r["event_id"] for r in ledger if r["category"] in ("execution", "rejected")}
        ),
        "total_play_events": len(all_events),
        "missing_source_events": len(all_events) - successful_events,
        "coverage": successful_events / max(1, len(all_events)),
        "skipped": dict(skipped),
        "collisions": collisions,
        "omitted_command_ticks": omitted,
        "source_event_stream_completed": complete,
        "normal_simulator_terminal": normal_terminal,
        "native_winner": native_winner,
        "native_crowns": native_state.get("crowns") if native_state else None,
        "source_or_native_terminal_completed": source_or_terminal,
        "trajectory_completion_kind": (
            "all_source_events"
            if complete
            else "normal_simulator_terminal"
            if normal_terminal
            else "incomplete"
        ),
        "all_source_events_executed": complete,
        "last_source_tick": source_last,
        "last_simulator_tick": int(info["tick"]),
        "simulator_episode_done": bool(vector.dones[0]),
        "simulator_match_decided": decided,
        "native_match_ended": native_state.get("match_ended") if native_state else None,
        "simulator_terminated": (bool(vector.dones[0]) or decided)
        and not fault
        and not bool(info.get("truncated", 0)),
        "simulator_truncated": bool(info.get("truncated", 0)),
        "pending_commands_settled": settled,
        "stop_reason": stop_reason,
        "source_declared_duration_ticks": config.source_end_tick,
        "reached_declared_end": (
            int(info["tick"]) >= config.source_end_tick
            if config.source_end_tick is not None
            else None
        ),
        "simulator_fault": fault,
        "early_terminal_before_last_source_event": (bool(vector.dones[0]) or decided)
        and successful_events < len(all_events),
        "native_run_refusals": run_refusals,
        "repair_records": ledger,
        "repair_summary": {
            "count": len(repair_records),
            "categories": dict(categories),
            "hand_replacements": hand_repairs,
            "tile_snaps": categories["tile_snap"],
        },
        "repair_class": "repaired" if repair_records else "unmodified_reconstruction",
        "repaired_from_tick": min((r["simulator_tick"] for r in repair_records), default=None),
        "dataset_kind": "repaired"
        if (config.repair_hand or config.repair_tile or config.repair_time)
        else "exact",
        "repair_is_exact_bc": not (config.repair_hand or config.repair_tile or config.repair_time),
        "label_source": "live_pre_action_capture",
        "native_replay_reproduces_repairs": False,
    }
    arrays = None
    if obs:
        arrays = {
            "observations": np.concatenate(obs),
            "masks": np.concatenate(masks),
            "actions": np.concatenate(labels),
            "ticks": np.array(times, np.int32),
            "seats": np.array(seats, np.int32),
            "flags": np.array(flags, np.int32),
        }
    return stats, arrays, executed, omitted
